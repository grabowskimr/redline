// Regenerates src/model/kindGlyphs.ts from the installed @vscode/codicons sprite.
//
// The kind → codicon mapping is owned by src/model/note.ts (KIND_META.themeIcon); it is
// read from there rather than duplicated, so changing an icon cannot leave the comment
// widget's avatar showing the previous one.
import { readFileSync, writeFileSync } from 'node:fs';

const note = readFileSync('src/model/note.ts', 'utf8');
const mapping = [...note.matchAll(/^\s{2}(\w+): \{ icon: '[^']*', themeIcon: '([^']+)'/gm)].map((m) => [
  m[1],
  m[2],
]);
if (mapping.length === 0) throw new Error('could not read KIND_META from src/model/note.ts');

const svg = readFileSync('node_modules/@vscode/codicons/dist/codicon.svg', 'utf8');
const entries = mapping.map(([kind, icon]) => {
  const symbol = new RegExp(`<symbol[^>]*id="${icon}"[^>]*>([\\s\\S]*?)</symbol>`).exec(svg);
  if (!symbol) throw new Error(`codicon "${icon}" (kind "${kind}") not found in the sprite`);
  // Keep every <path> and its attributes: fill-rule="evenodd" changes what gets filled,
  // and concatenating the outlines into one path would render some icons as blobs.
  const paths = [...symbol[1].matchAll(/<path\b[^>]*\/>/g)].map((m) => m[0]);
  if (paths.length === 0) throw new Error(`codicon "${icon}" has no <path>`);
  return `  ${kind}:\n    '${paths.join('').replace(/'/g, "\\'")}',`;
});

writeFileSync(
  'src/model/kindGlyphs.ts',
  `/**\n * Codicon markup for each note kind, extracted from \`@vscode/codicons\` (16×16 symbol\n * sprite). The comment widget only accepts an image for its author icon, so the glyph is\n * drawn into an SVG data URI instead of being referenced by name.\n *\n * Generated by scripts/generate-kind-glyphs.mjs — run \`npm run codicons:glyphs\`.\n */\nimport { NoteKind } from './note';\n\nexport const KIND_GLYPH: Record<NoteKind, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`wrote ${entries.length} glyphs`);
